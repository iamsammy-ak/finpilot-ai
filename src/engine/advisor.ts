/**
 * FinPilot's analyst is a deterministic engine, not a language model.
 * It matches a question to one of the analyses below and fills every sentence
 * with figures computed from the snapshot. No network call is made and no
 * text is generated by an external AI.
 */

export interface AnswerNumber {
  label: string;
  value: string;
  tone?: 'good' | 'bad';
}

export interface Answer {
  intent: string;
  headline: string;
  /** What data the answer is based on. */
  basis: string;
  observations: string[];
  numbers: AnswerNumber[];
  patterns: string[];
  problems: string[];
  actions: string[];
  followUps: string[];
}

export const SUGGESTED_QUESTIONS = [
  'Where is most of my money going?',
  'Why did my expenses increase this month?',
  'How much can I realistically save?',
  'Which subscriptions should I cancel?',
  'How much am I spending on restaurants?',
  'Am I spending more than I earn?',
  'How much money will I have at the end of the month?',
  'What should I improve financially?',
];

const CATEGORY_ALIASES: [RegExp, Category][] = [
  [/\b(rent|housing|mortgage)\b/, 'Housing'],
  [/\b(grocer\w*|supermarket\w*|food shopping)\b/, 'Groceries'],
  [/\b(restaurant\w*|dining|eating out|eat out|takeaway|take-?out|delivery|caf[eé]s?|coffee)\b/, 'Restaurants'],
  [/\b(transport\w*|transit|commut\w*|fuel|petrol|taxi)\b/, 'Transportation'],
  [/\b(shopping|clothes|clothing)\b/, 'Shopping'],
  [/\b(entertainment|fun|leisure|cinema|games?)\b/, 'Entertainment'],
  [/\b(education|courses?|tuition|books?)\b/, 'Education'],
  [/\b(health\w*|medical|pharmacy|doctor)\b/, 'Healthcare'],
  [/\b(utilit\w*|electricity|internet|phone bill|bills)\b/, 'Utilities'],
  [/\b(travel\w*|holiday|vacation|flights?|trips?)\b/, 'Travel'],
  [/\b(freelanc\w*)\b/, 'Freelance Income'],
  [/\b(investments?|dividends?)\b/, 'Investments'],
];

const INTENTS: [string, RegExp][] = [
  ['monthEnd', /end of (the|this|that) month|month[- ]?end|by the end|will i have|have left|left over/],
  ['subscriptions', /subscri|cancel|streaming|memberships?/],
  ['save', /how much.*sav|realistic|can i save|could i save|saving(s)? potential|save more|afford to save|increase (my )?savings/],
  ['increase', /why.*(increas|higher|more|rise|rose|went up|go up|grow|jump|spik)|(increas|went up|higher than|rose|jump)/],
  ['earnVsSpend', /more than i (earn|make)|overspend|within my means|beyond my means|spend(ing)? more than|in the red|deficit|cash ?flow/],
  ['largest', /(largest|biggest|most expensive|top) (purchase|transaction|payment|expense)s?/],
  ['topSpending', /where.*(money|spend)|most of my money|money go|biggest categor|top categor|break ?down|what do i spend/],
  ['budget', /budget/],
  ['health', /\bhealth\b|score/],
  ['forecast', /next month|forecast|predict|projection|outlook/],
  ['improve', /improve|should i (do|change|fix)|advice|advise|tips?|recommend|do better|priorit/],
  ['recurring', /recurring|fixed costs?|regular payments?|bills? due|upcoming/],
  ['income', /income|earn|salary|paid|make a month/],
  ['balance', /balance|how much (money )?do i have|net worth/],
  ['anomaly', /unusual|anomal|odd|strange|out of the ordinary|suspicious/],
];

const FIXED: Category[] = ['Housing', 'Utilities', 'Subscriptions'];

export function detectIntent(question: string, s: Snapshot): { intent: string; category?: Category; merchant?: string } {
  const q = question.toLowerCase();
  let category: Category | undefined = CATEGORIES.find((c) => q.includes(c.toLowerCase()));
  if (!category) category = CATEGORY_ALIASES.find(([re]) => re.test(q))?.[1];

  const merchants = byMerchant(s.txs).concat(byMerchant(s.txs, 'income'));
  const merchant = merchants.find((m) => m.key.length >= 3 && q.includes(m.key))?.merchant;

  for (const [intent, re] of INTENTS) {
    if (!re.test(q)) continue;
    // "How much am I spending on restaurants" is a category question even though it says "spend".
    if (intent === 'topSpending' && category) return { intent: 'category', category };
    if (intent === 'income' && category && !['Salary', 'Freelance Income', 'Investments'].includes(category)) {
      return { intent: 'category', category };
    }
    return { intent, category, merchant };
  }
  if (merchant) return { intent: 'merchant', merchant };
  if (category) return { intent: 'category', category };
  return { intent: 'fallback' };
}

const list = (items: string[]) =>
  items.length <= 1 ? (items[0] ?? '') : `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`;

export function answerQuestion(question: string, s: Snapshot): Answer {
  const { intent, category, merchant } = detectIntent(question, s);
  const period = s.range.label;
  const vs = s.compare.previous.label;
  const t = s.totals;
  const p = s.previousTotals;
  const m = monthLabel(s.focusMonth);
  const toDate = s.focusInProgress && s.singleMonth ? ' to date' : '';
  const basis = `${period}${toDate} · ${plural(s.rangeTx.length, 'transaction')} analysed`;
  const flexibleCats = s.categories.filter((c) => !FIXED.includes(c.category));
  const overBudget = s.budget.rows.filter((r) => r.level === 'over');

  const base = (a: Omit<Answer, 'intent' | 'basis'> & { basis?: string }): Answer => ({ intent, basis, ...a });
  const none = (what: string) => [`No ${what} detected in ${period}.`];

  if (!s.txs.length) {
    return base({
      headline: 'There are no transactions to analyse yet.',
      observations: ['Add transactions manually, import a CSV bank statement, or load the demo data from Settings.'],
      numbers: [],
      patterns: [],
      problems: [],
      actions: ['Go to Transactions and choose “Import CSV” or “Add transaction”.'],
      followUps: [],
    });
  }

  switch (intent) {
    /* -------------------------------------------------------------------- */
    case 'topSpending': {
      const top = s.categories.slice(0, 5);
      const fixed = round2(s.categories.filter((c) => FIXED.includes(c.category)).reduce((a, c) => a + c.amount, 0));
      const merchants = byMerchant(s.rangeTx).slice(0, 3);
      const flex = flexibleCats[0];
      return base({
        headline: top.length
          ? `${top[0].category} takes the largest share: ${money(top[0].amount)}, ${pct(top[0].share, 0)} of what you spent.`
          : `You have no spending recorded in ${period}.`,
        observations: [
          `You spent ${money(t.expenses)} in ${period}${toDate} across ${plural(s.rangeTx.filter((x) => x.type === 'expense').length, 'purchase')}.`,
          top.length >= 3
            ? `The top three categories — ${list(top.slice(0, 3).map((c) => c.category))} — account for ${pct(top.slice(0, 3).reduce((a, c) => a + c.share, 0), 0)} of spending.`
            : '',
        ].filter(Boolean),
        numbers: [...top.map((c) => ({ label: `${c.category} (${pct(c.share, 0)})`, value: money(c.amount) })), { label: 'Total spending', value: money(t.expenses) }],
        patterns: [
          t.expenses > 0
            ? `Fixed costs (housing, utilities, subscriptions) are ${money(fixed)} — ${pct(fixed / t.expenses, 0)} of spending. The remaining ${money(t.expenses - fixed)} is flexible.`
            : '',
          merchants.length ? `Your top merchants are ${list(merchants.map((x) => `${x.merchant} (${money(x.amount)})`))}.` : '',
        ].filter(Boolean),
        problems: overBudget.length
          ? overBudget.map((r) => `${r.category} is ${money(r.spent - r.budget)} over its ${money(r.budget)} budget for ${m}.`)
          : none('over-budget categories'),
        actions: flex
          ? [
              `${flex.category} is your largest flexible category at ${money(flex.amount)}. Cutting it by 15% frees about ${money(flex.amount * 0.15)}.`,
              'Fixed costs only change with bigger decisions (renegotiating rent, switching providers), so start with flexible categories.',
            ]
          : ['Nearly all of your spending is fixed costs — review providers and contracts for savings.'],
        followUps: [flex ? `How much am I spending on ${flex.category.toLowerCase()}?` : SUGGESTED_QUESTIONS[4], SUGGESTED_QUESTIONS[1], SUGGESTED_QUESTIONS[2]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'increase': {
      const deltas = category ? s.categoryChanges.filter((c) => c.category === category) : s.categoryChanges;
      const cur = category ? (deltas[0]?.current ?? 0) : t.expenses;
      const prev = category ? (deltas[0]?.previous ?? 0) : p.expenses;
      const diff = round2(cur - prev);
      const what = category ? `${category} spending` : 'spending';
      const risers = deltas.filter((c) => c.delta > 0.5).sort((a, b) => b.delta - a.delta);
      const fallers = s.categoryChanges.filter((c) => c.delta < -0.5).sort((a, b) => a.delta - b.delta);
      const curTx = inRange(s.txs, s.compare.current.from, s.compare.current.to).filter((x) => x.type === 'expense');
      const drivers = risers.slice(0, 2).flatMap((r) => {
        const big = curTx.filter((x) => x.category === r.category).sort((a, b) => b.amount - a.amount)[0];
        return big ? [`Largest ${r.category} item: ${big.merchant}, ${money(big.amount)} on ${fmtDayMonth(big.date)}.`] : [];
      });
      const nCur = curTx.length;
      const nPrev = s.previousTx.filter((x) => x.type === 'expense').length;
      if (prev === 0) {
        return base({
          headline: `There is no earlier period to compare ${period} with.`,
          observations: [`You spent ${money(cur)} on ${category ?? 'everything'} in ${period}${toDate}, but ${vs} has no ${what} recorded.`],
          numbers: [{ label: period, value: money(cur) }],
          patterns: [],
          problems: [],
          actions: ['Import an older statement or pick a later period in the date selector to compare.'],
          followUps: [SUGGESTED_QUESTIONS[0], SUGGESTED_QUESTIONS[4]],
        });
      }
      return base({
        headline:
          diff > 0
            ? `Your ${what} is up ${money(diff)} (${pctSigned(diff / prev)}) against ${vs}${risers[0] && !category ? `, driven mostly by ${risers[0].category}` : ''}.`
            : `Your ${what} did not increase — it is ${money(Math.abs(diff))} (${pct(Math.abs(diff) / prev)}) lower than ${vs}.`,
        observations: [
          `${period}${toDate}: ${money(cur)}. ${vs}: ${money(prev)}.`,
          ...risers.slice(0, 3).map((r) => `${r.category} rose ${money(r.delta)}${r.change !== null ? ` (${pctSigned(r.change, 0)})` : ' (nothing in the earlier period)'}: ${money(r.previous)} → ${money(r.current)}.`),
        ],
        numbers: [
          { label: `${period}${toDate}`, value: money(cur) },
          { label: `Compared with ${vs}`, value: money(prev) },
          { label: 'Change', value: moneySigned(diff), tone: diff > 0 ? 'bad' : 'good' },
          ...risers.slice(0, 3).map((r) => ({ label: `${r.category} change`, value: moneySigned(r.delta), tone: 'bad' as const })),
        ],
        patterns: [
          ...drivers,
          `You made ${plural(nCur, 'purchase')} against ${nPrev} before; the average purchase went from ${money(nPrev ? p.expenses / nPrev : 0)} to ${money(nCur ? t.expenses / nCur : 0)}.`,
          !category && fallers.length ? `Partly offset by lower ${list(fallers.slice(0, 2).map((f) => `${f.category} (${moneySigned(f.delta)})`))}.` : '',
        ].filter(Boolean),
        problems: s.anomalies.length ? s.anomalies.slice(0, 2).map((a) => `${a.title} — ${a.detail}`) : none('one-off outliers'),
        actions:
          diff > 0 && risers.length
            ? [
                `Returning ${risers[0].category} to its earlier level would recover ${money(risers[0].delta)}.`,
                s.anomalies.some((a) => a.kind === 'transaction')
                  ? 'One-off purchases explain part of the rise; they will not repeat unless you choose to.'
                  : 'The rise is spread across regular purchases rather than one-offs, so it will persist unless habits change.',
              ]
            : ['No action needed — keep the current pace.'],
        followUps: [risers[0] ? `How much am I spending on ${risers[0].category.toLowerCase()}?` : SUGGESTED_QUESTIONS[0], SUGGESTED_QUESTIONS[5], SUGGESTED_QUESTIONS[7]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'save': {
      const complete = s.monthly.filter((x) => !x.inProgress && x.count > 0).slice(-3);
      const months = complete.length || 1;
      const income = complete.length ? complete.reduce((a, x) => a + x.income, 0) / months : s.projection.income;
      const expenses = complete.length ? complete.reduce((a, x) => a + x.expenses, 0) / months : s.projection.expenses;
      const fixed = round2(s.recurring.filter((r) => r.type === 'expense' && r.nextDate).reduce((a, r) => a + r.amount, 0));
      const flexible = Math.max(0, expenses - fixed);
      const now = income - expenses;
      const comfortable = now + flexible * 0.1;
      const stretch = now + flexible * 0.2;
      const overlap = overlappingSubscriptions(s)[0];
      const target = s.settings.savingsRateTarget;
      return base({
        basis: complete.length ? `Average of your last ${plural(complete.length, 'complete month')}` : `${m} projection (no complete month yet)`,
        headline: `Realistically, about ${money(comfortable)} a month — ${pct(income > 0 ? comfortable / income : 0, 0)} of your income.`,
        observations: [
          `You currently keep ${money(now)} a month on average: ${money(income)} in, ${money(expenses)} out (a ${pct(income > 0 ? now / income : 0)} savings rate).`,
          `${money(fixed)} of your spending is recurring commitments you cannot easily change month to month. The other ${money(flexible)} is flexible.`,
        ],
        numbers: [
          { label: 'Average monthly income', value: money(income) },
          { label: 'Recurring commitments', value: money(fixed) },
          { label: 'Flexible spending', value: money(flexible) },
          { label: 'Saving now', value: money(now), tone: now >= 0 ? 'good' : 'bad' },
          { label: 'Comfortable (flexible −10%)', value: money(comfortable), tone: 'good' },
          { label: 'Stretch (flexible −20%)', value: money(stretch), tone: 'good' },
        ],
        patterns: [
          complete.length >= 2
            ? `Your monthly surplus ranged from ${money(Math.min(...complete.map((x) => x.net)))} to ${money(Math.max(...complete.map((x) => x.net)))} over those months.`
            : 'With less than two complete months of data this estimate will sharpen as history builds up.',
        ],
        problems:
          income > 0 && now / income < target
            ? [`Your average savings rate of ${pct(now / income)} is below your ${pct(target, 0)} target — the gap is ${money(target * income - now)} a month.`]
            : [`No problem here: you already meet your ${pct(target, 0)} savings target on average.`],
        actions: [
          `Move ${money(comfortable)} to savings on payday rather than saving whatever is left over.`,
          flexibleCats[0] ? `The 10% trim is easiest in ${list(flexibleCats.slice(0, 2).map((c) => c.category))}, your largest flexible categories.` : '',
          overlap ? `Cancel ${overlap.items[overlap.items.length - 1].merchant} (${money(overlap.items[overlap.items.length - 1].amount)} a month) if you do not need two ${overlap.kind} services.` : '',
        ].filter(Boolean),
        followUps: [SUGGESTED_QUESTIONS[3], SUGGESTED_QUESTIONS[0], 'What does next month look like?'],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'subscriptions': {
      const subs = s.subscriptions;
      const overlaps = overlappingSubscriptions(s);
      if (!subs.length) {
        return base({
          headline: 'I could not find any active subscriptions in your transactions.',
          observations: ['A subscription is detected when a merchant in the Subscriptions category charges you, or the same merchant bills a stable amount monthly.'],
          numbers: [],
          patterns: [],
          problems: [],
          actions: ['If you do have subscriptions, check they are categorised as Subscriptions on the Transactions page.'],
          followUps: [SUGGESTED_QUESTIONS[0], SUGGESTED_QUESTIONS[2]],
        });
      }
      const avgExp = s.forecast.modelExpenses || t.expenses;
      return base({
        basis: `${plural(subs.length, 'active subscription')} found across all transactions`,
        headline: overlaps.length
          ? `Start with ${overlaps[0].items[overlaps[0].items.length - 1].merchant}: it overlaps with ${overlaps[0].items[0].merchant}.`
          : `You have ${plural(subs.length, 'subscription')} costing ${money(s.subscriptionMonthly)} a month — none obviously overlap.`,
        observations: [
          `Your subscriptions total ${money(s.subscriptionMonthly)} a month, or ${money(s.subscriptionMonthly * 12)} a year.`,
          ...overlaps.map((g) => `You pay for ${g.items.length} ${g.kind} services: ${list(g.items.map((i) => `${i.merchant} (${money(i.amount)})`))}.`),
        ],
        numbers: [...subs.map((r) => ({ label: `${r.merchant} · next ${r.nextDate ? fmtDayMonth(r.nextDate) : '—'}`, value: `${money(r.amount)}/mo` })), { label: 'Total per year', value: money(s.subscriptionMonthly * 12) }],
        patterns: [
          avgExp > 0 ? `Subscriptions are ${pct(s.subscriptionMonthly / avgExp)} of a typical month's spending.` : '',
          `The most expensive is ${subs[0].merchant} at ${money(subs[0].amount * 12)} a year.`,
        ].filter(Boolean),
        problems: overlaps.length
          ? overlaps.map((g) => `Overlap: ${g.items.length} ${g.kind} services cost ${money(g.items.reduce((a, i) => a + i.amount, 0))} a month together.`)
          : none('overlapping subscriptions'),
        actions: [
          ...overlaps.map((g) => {
            const drop = g.items[g.items.length - 1];
            return `Cancel ${drop.merchant} to save ${money(drop.amount)} a month (${money(drop.amount * 12)} a year), or rotate services month by month instead of holding both.`;
          }),
          'I can see what you pay, not how much you use each service — cancel anything you have not opened in the last month.',
        ],
        followUps: [SUGGESTED_QUESTIONS[2], 'What recurring payments are coming up?', SUGGESTED_QUESTIONS[7]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'category': {
      const cat = category as Category;
      const isIncome = ['Salary', 'Freelance Income', 'Investments'].includes(cat);
      const type = isIncome ? 'income' : 'expense';
      const rows = s.rangeTx.filter((x) => x.category === cat && x.type === type);
      const total = round2(rows.reduce((a, x) => a + x.amount, 0));
      const prevTotal = round2(s.previousTx.filter((x) => x.category === cat && x.type === type).reduce((a, x) => a + x.amount, 0));
      const share = (isIncome ? t.income : t.expenses) > 0 ? total / (isIncome ? t.income : t.expenses) : 0;
      const merchants = byMerchant(rows, type).slice(0, 3);
      const biggest = [...rows].sort((a, b) => b.amount - a.amount)[0];
      const budget = s.budget.rows.find((r) => r.category === cat);
      const verb = isIncome ? 'received' : 'spent';
      if (!rows.length) {
        return base({
          headline: `You have no ${cat} transactions in ${period}.`,
          observations: [prevTotal > 0 ? `For comparison, ${vs} had ${money(prevTotal)}.` : `Nothing in the comparison period (${vs}) either.`],
          numbers: [],
          patterns: [],
          problems: [],
          actions: ['Pick a wider period in the date selector if you expected to see activity here.'],
          followUps: [SUGGESTED_QUESTIONS[0]],
        });
      }
      const diff = round2(total - prevTotal);
      return base({
        headline: `You ${verb} ${money(total)} on ${cat} in ${period}${toDate} — ${pct(share, 0)} of your ${isIncome ? 'income' : 'spending'}.`,
        observations: [
          `That is ${plural(rows.length, 'transaction')} averaging ${money(total / rows.length)} each.`,
          prevTotal > 0
            ? `Against ${vs} (${money(prevTotal)}) that is ${diff >= 0 ? 'up' : 'down'} ${money(Math.abs(diff))}, or ${pctSigned(diff / prevTotal, 0)}.`
            : `There was no ${cat} activity in ${vs} to compare with.`,
        ],
        numbers: [
          { label: `${cat}, ${period}`, value: money(total) },
          { label: `Compared with ${vs}`, value: money(prevTotal) },
          { label: 'Transactions', value: String(rows.length) },
          { label: 'Average each', value: money(total / rows.length) },
          ...(budget ? [{ label: `Budget used (${m})`, value: `${pct(budget.used, 0)} of ${money(budget.budget)}`, tone: budget.level === 'over' ? ('bad' as const) : undefined }] : []),
        ],
        patterns: [
          merchants.length ? `Mostly at ${list(merchants.map((x) => `${x.merchant} (${money(x.amount)}, ${x.count}×)`))}.` : '',
          biggest ? `Largest single item: ${biggest.merchant}, ${money(biggest.amount)} on ${fmtDate(biggest.date)}.` : '',
        ].filter(Boolean),
        problems: isIncome
          ? []
          : budget && budget.level !== 'ok'
            ? [budget.level === 'over' ? `You are ${money(budget.spent - budget.budget)} over the ${money(budget.budget)} budget for ${m}.` : `You have used ${pct(budget.used, 0)} of the ${m} budget with ${money(budget.remaining)} left.`]
            : !budget
              ? [`There is no budget set for ${cat}, so nothing warns you when it grows.`]
              : [`Within budget: ${money(budget.remaining)} of ${money(budget.budget)} left for ${m}.`],
        actions: isIncome
          ? ['Income categories are tracked for cash flow; see the Cash Flow page for the month-by-month picture.']
          : [
              merchants[0] && merchants[0].count >= 2 ? `${merchants[0].merchant} alone is ${money(merchants[0].amount)} over ${merchants[0].count} visits — one fewer a month saves about ${money(merchants[0].amount / merchants[0].count)}.` : '',
              !budget ? `Set a ${cat} budget of about ${money(Math.ceil((total * 1.05) / 5) * 5)} on the Budgets page.` : '',
              diff > 15 && prevTotal > 0 ? `Getting back to the earlier level would save ${money(diff)}.` : '',
            ].filter(Boolean),
        followUps: [SUGGESTED_QUESTIONS[1], SUGGESTED_QUESTIONS[0], 'Am I within my budgets?'],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'earnVsSpend': {
      const pr = s.projection;
      const recent = s.monthly.filter((x) => x.count > 0).slice(-4);
      const negative = recent.filter((x) => x.net < 0);
      const spendingMore = t.net < 0;
      return base({
        headline: spendingMore
          ? `Yes — in ${period}${toDate} you spent ${money(Math.abs(t.net))} more than you earned.`
          : `No — in ${period}${toDate} you earned ${money(t.net)} more than you spent.`,
        observations: [
          `Income ${money(t.income)}, spending ${money(t.expenses)}: you spend ${t.income > 0 ? pct(t.expenses / t.income, 0) : 'all'} of what comes in.`,
          pr.isProjected ? `If ${m} continues at your usual pace it ends at ${money(pr.income)} in and ${money(pr.expenses)} out — ${pr.net >= 0 ? 'a surplus' : 'a shortfall'} of ${money(Math.abs(pr.net))}.` : '',
        ].filter(Boolean),
        numbers: [
          { label: 'Income', value: money(t.income) },
          { label: 'Spending', value: money(t.expenses) },
          { label: 'Net', value: moneySigned(t.net), tone: t.net >= 0 ? 'good' : 'bad' },
          ...recent.map((x) => ({ label: `${monthLabel(x.month)}${x.inProgress ? ' (so far)' : ''}`, value: moneySigned(x.net), tone: x.net >= 0 ? ('good' as const) : ('bad' as const) })),
        ],
        patterns: [
          negative.length
            ? `You ran a deficit in ${negative.length} of the last ${recent.length} months (${list(negative.map((x) => monthLabel(x.month)))}).`
            : `Income exceeded spending in each of the last ${plural(recent.length, 'month')} on record.`,
        ],
        problems: spendingMore || pr.net < 0 ? [`A deficit is paid from your balance, which stands at ${money(s.balanceNow)}.`] : none('deficit'),
        actions: spendingMore
          ? [`Close the ${money(Math.abs(t.net))} gap first: ${flexibleCats[0] ? `${flexibleCats[0].category} (${money(flexibleCats[0].amount)}) is the largest flexible category` : 'review your largest categories'}.`]
          : [`Keep the surplus working: move ${money(Math.max(0, t.net))} to savings so it is not absorbed by everyday spending.`],
        followUps: [SUGGESTED_QUESTIONS[2], SUGGESTED_QUESTIONS[6], SUGGESTED_QUESTIONS[0]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'monthEnd': {
      const cur = monthKey(s.today);
      const pr = s.focusMonth === cur ? s.projection : projectMonth(s.txs, cur, s.today, s.recurring);
      const bills = round2(pr.pendingBills.reduce((a, b) => a + b.amount, 0));
      const end = round2(s.balanceNow + pr.pendingIncome - bills - pr.variableRemaining);
      const start = s.monthly.find((x) => x.month === cur)?.opening ?? s.balanceNow;
      return base({
        basis: `Balance today plus a projection for the ${pr.daysLeft} days left in ${monthLabel(cur)}`,
        headline: pr.isProjected
          ? `About ${money(end)} — an estimate, not a certainty.`
          : `${monthLabel(cur)} is complete: your balance is ${money(s.balanceNow)}.`,
        observations: [
          `Your balance today is ${money(s.balanceNow)}.`,
          pr.pendingBills.length ? `${plural(pr.pendingBills.length, 'recurring bill')} still due this month: ${list(pr.pendingBills.map((b) => `${b.merchant} ${money(b.amount)} (${fmtDayMonth(b.date)})`))}.` : 'No recurring bills are still due this month.',
          pr.isProjected ? `Everyday spending runs at about ${money(pr.dailyVariable)} a day, so ${money(pr.variableRemaining)} over the remaining ${pr.daysLeft} days.` : '',
        ].filter(Boolean),
        numbers: [
          { label: 'Balance today', value: money(s.balanceNow) },
          { label: 'Income still expected', value: moneySigned(pr.pendingIncome), tone: 'good' },
          { label: 'Bills still due', value: moneySigned(-bills) },
          { label: `Everyday spending, ${pr.daysLeft} days`, value: moneySigned(-pr.variableRemaining) },
          { label: 'Estimated month-end balance', value: money(end), tone: end >= start ? 'good' : 'bad' },
        ],
        patterns: [
          `That would be ${moneySigned(end - start)} against the ${money(start)} you started ${monthLabel(cur)} with.`,
          pr.basis,
        ],
        problems: end < start ? [`You are on track to end the month ${money(start - end)} below where you started.`] : none('month-end shortfall'),
        actions: [
          pr.isProjected ? `Every ${money(5)} a day you trim from everyday spending adds ${money(5 * pr.daysLeft)} to the month-end balance.` : 'See the Forecast page for next month’s outlook.',
        ],
        followUps: ['What does next month look like?', SUGGESTED_QUESTIONS[5], 'What recurring payments are coming up?'],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'improve':
    case 'health': {
      const h = s.health;
      const sorted = [...h.components].sort((a, b) => a.score - b.score);
      const issues = s.insights.filter((i) => i.tone === 'warn' || i.tone === 'bad');
      return base({
        basis: `Financial health score for ${m}${h.isProjected ? ' (month still running, projected)' : ''}`,
        headline:
          intent === 'health'
            ? `Your financial health score is ${h.score}/100 — ${h.grade.toLowerCase()}.`
            : `Your biggest lever is ${sorted[0].label.toLowerCase()}: it scores ${Math.round(sorted[0].score)}/100.`,
        observations: [
          `Overall score ${h.score}/100 (${h.grade.toLowerCase()})${h.previous ? `, ${h.score >= h.previous.score ? 'up' : 'down'} ${Math.abs(h.score - h.previous.score)} from ${h.previous.score} in ${monthLabel(h.previous.month)}` : ''}.`,
          ...sorted.slice(0, 2).map((c) => `${c.label}: ${Math.round(c.score)}/100 — ${c.value}.`),
        ],
        numbers: h.components.map((c) => ({ label: c.label, value: `${c.points.toFixed(1)} / 25`, tone: c.score >= 85 ? ('good' as const) : c.score < 55 ? ('bad' as const) : undefined })),
        patterns: h.changes.length ? h.changes.slice(0, 3).map((c) => `${c.label} ${c.delta > 0 ? 'added' : 'cost'} ${Math.abs(c.delta).toFixed(1)} points: ${c.text}.`) : ['No earlier month to compare the score with yet.'],
        problems: issues.length ? issues.slice(0, 3).map((i) => `${i.title}. ${i.body}`) : none('urgent problems'),
        actions: h.recommendations,
        followUps: [SUGGESTED_QUESTIONS[2], 'Am I within my budgets?', SUGGESTED_QUESTIONS[3]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'budget': {
      const b = s.budget;
      const rows = category ? b.rows.filter((r) => r.category === category) : b.rows;
      if (!b.rows.length) {
        return base({
          headline: 'You have not set any budgets yet.',
          observations: [`You have spent ${money(b.totalSpent)} in ${m}.`],
          numbers: [],
          patterns: [],
          problems: ['Without budgets there is nothing to warn you when a category grows.'],
          actions: ['Open the Budgets page — it suggests a starting budget for each category from your own history.'],
          followUps: [SUGGESTED_QUESTIONS[0]],
        });
      }
      const flagged = b.rows.filter((r) => r.level !== 'ok' && r.level !== 'full').sort((x, y) => y.used - x.used);
      const daysLeft = s.focusInProgress ? daysInMonth(s.focusMonth) - dayOf(s.today) : 0;
      const left = round2(b.monthlyBudget - b.totalSpent);
      return base({
        basis: `Budgets for ${m}${s.focusInProgress ? `, ${pct(b.elapsed, 0)} of the month gone` : ''}`,
        headline:
          overBudget.length > 0
            ? `${plural(overBudget.length, 'category', 'categories')} over budget in ${m}: ${list(overBudget.map((r) => r.category))}.`
            : `You are within every budget in ${m}, with ${money(left)} of ${money(b.monthlyBudget)} left.`,
        observations: [
          `You have used ${pct(b.totalUsed, 0)} of your ${money(b.monthlyBudget)} monthly budget (${money(b.totalSpent)} spent).`,
          flagged.length ? `${plural(flagged.length, 'category', 'categories')} at 80% or more (excluding fixed costs that exactly match their budget): ${list(flagged.map((r) => `${r.category} ${pct(r.used, 0)}`))}.` : 'No flexible category has reached 80% of its budget.',
        ],
        numbers: (rows.length ? rows : b.rows)
          .slice()
          .sort((x, y) => y.used - x.used)
          .slice(0, 6)
          .map((r) => ({ label: r.category, value: `${money(r.spent)} / ${money(r.budget)}`, tone: r.level === 'over' ? ('bad' as const) : undefined })),
        patterns: [
          s.focusInProgress && left > 0 && daysLeft > 0 ? `That leaves about ${money(left / daysLeft)} a day for the remaining ${daysLeft} days.` : '',
          b.unbudgeted.length ? `Spending without a budget: ${list(b.unbudgeted.map((u) => `${u.category} ${money(u.spent)}`))}.` : '',
        ].filter(Boolean),
        problems: overBudget.length ? overBudget.map((r) => `${r.category}: ${money(r.spent)} against ${money(r.budget)} — ${money(r.spent - r.budget)} over.`) : none('overspending'),
        actions: overBudget.length
          ? [`Pause ${overBudget[0].category} spending for the rest of the month, or accept the overrun and cut ${money(b.overspend)} elsewhere.`]
          : ['Stay the course. The Budgets page lists adjustments based on your last three months.'],
        followUps: [SUGGESTED_QUESTIONS[7], SUGGESTED_QUESTIONS[0], SUGGESTED_QUESTIONS[6]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'forecast': {
      const f = s.forecast;
      const [con, exp, opt] = f.scenarios;
      return base({
        basis: f.thinHistory ? 'Estimate from the running month only — treat with caution' : `Estimate from ${plural(f.basisMonths.length, 'complete month')} of history`,
        headline: `For ${f.targetLabel} I estimate ${money(exp.income)} in, ${money(exp.expenses)} out, and ${money(exp.savings)} saved.`,
        observations: [
          `Expected end balance: ${money(exp.endBalance)}, starting from ${f.startIsProjected ? 'a projected' : 'an actual'} ${money(f.startBalance)}.`,
          `The range runs from ${money(con.savings)} saved (conservative) to ${money(opt.savings)} (optimistic).`,
        ],
        numbers: f.scenarios.map((x) => ({ label: `${x.label}: saved / end balance`, value: `${money(x.savings)} / ${money(x.endBalance)}`, tone: x.savings >= 0 ? ('good' as const) : ('bad' as const) })),
        patterns: [
          f.categories.length ? `Largest projected categories: ${list(f.categories.slice(0, 3).map((c) => `${c.category} ${money(c.amount)}`))}.` : '',
          'Method: a recency-weighted average of recent months plus half of the recent trend, per category.',
        ].filter(Boolean),
        problems: con.savings < 0 ? [`In the conservative scenario you would spend ${money(Math.abs(con.savings))} more than you earn.`] : none('shortfall in any scenario'),
        actions: [exp.meetsTarget ? `The expected scenario meets your ${money(s.forecast.scenarios[1].savings - exp.gap)} savings target.` : `The expected scenario misses your savings target by ${money(Math.abs(exp.gap))} — adjust assumptions on the Forecast page to see what closes the gap.`],
        followUps: [SUGGESTED_QUESTIONS[6], SUGGESTED_QUESTIONS[2], SUGGESTED_QUESTIONS[7]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'recurring': {
      const exp = s.recurring.filter((r) => r.type === 'expense' && r.nextDate);
      const total = round2(exp.reduce((a, r) => a + r.amount, 0));
      const next7 = s.upcoming.filter((u) => u.daysAway <= 7);
      return base({
        basis: `${plural(exp.length, 'recurring payment')} detected across all transactions`,
        headline: exp.length ? `You have ${money(total)} of recurring payments each month across ${plural(exp.length, 'merchant')}.` : 'I could not detect any recurring payments yet.',
        observations: [
          next7.length ? `Due in the next 7 days: ${list(next7.map((u) => `${u.merchant} ${money(u.amount)} (${fmtDayMonth(u.nextDate)})`))}.` : 'Nothing is due in the next 7 days.',
          s.forecast.modelIncome > 0 ? `Recurring payments take ${pct(total / s.forecast.modelIncome, 0)} of a typical month's income.` : '',
        ].filter(Boolean),
        numbers: s.upcoming.slice(0, 8).map((u) => ({ label: `${u.merchant} · ${fmtDayMonth(u.nextDate)}`, value: money(u.amount) })),
        patterns: ['A payment counts as recurring when the same merchant charges a stable amount (within 10%) on a stable day (within 4 days) in two or more consecutive months.'],
        problems: next7.reduce((a, u) => a + u.amount, 0) > s.balanceNow ? ['Payments due this week exceed your current balance.'] : none('payment risk'),
        actions: ['Review the full list on the Cash Flow page and cancel anything you no longer use.'],
        followUps: [SUGGESTED_QUESTIONS[3], SUGGESTED_QUESTIONS[6]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'income': {
      const sources = byCategory(s.rangeTx, 'income');
      const payers = byMerchant(s.rangeTx, 'income').slice(0, 3);
      const diff = round2(t.income - p.income);
      return base({
        headline: `You received ${money(t.income)} in ${period}${toDate}.`,
        observations: [
          sources.length ? `Sources: ${list(sources.map((c) => `${c.category} ${money(c.amount)} (${pct(c.share, 0)})`))}.` : 'No income is recorded in this period.',
          p.income > 0 ? `Against ${vs} (${money(p.income)}) that is ${moneySigned(diff)}.` : '',
        ].filter(Boolean),
        numbers: [...sources.map((c) => ({ label: c.category, value: money(c.amount) })), { label: 'Total income', value: money(t.income) }, { label: 'Kept after spending', value: moneySigned(t.net), tone: t.net >= 0 ? ('good' as const) : ('bad' as const) }],
        patterns: [payers.length ? `Paid by ${list(payers.map((x) => `${x.merchant} (${money(x.amount)})`))}.` : '', sources.length === 1 ? 'All of your income comes from a single source.' : ''].filter(Boolean),
        problems: sources.length === 1 ? ['A single income source means any interruption hits 100% of your income — a cash buffer matters more.'] : none('income concentration risk'),
        actions: [`You keep ${pct(t.savingsRate)} of this income. Your target is ${pct(s.settings.savingsRateTarget, 0)}.`],
        followUps: [SUGGESTED_QUESTIONS[5], SUGGESTED_QUESTIONS[2]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'largest': {
      const top = s.rangeTx.filter((x) => x.type === 'expense').sort((a, b) => b.amount - a.amount).slice(0, 5);
      return base({
        headline: top.length ? `Your largest payment in ${period} was ${top[0].merchant}: ${money(top[0].amount)}.` : `No spending recorded in ${period}.`,
        observations: [top.length ? `Your five largest payments add up to ${money(top.reduce((a, x) => a + x.amount, 0))} — ${pct(t.expenses > 0 ? top.reduce((a, x) => a + x.amount, 0) / t.expenses : 0, 0)} of all spending.` : ''].filter(Boolean),
        numbers: top.map((x: Transaction) => ({ label: `${x.merchant} · ${fmtDayMonth(x.date)} · ${x.category}`, value: money(x.amount) })),
        patterns: [top.filter((x) => FIXED.includes(x.category)).length ? `${top.filter((x) => FIXED.includes(x.category)).length} of the five are fixed costs.` : 'None of the five are fixed costs — they were all choices.'],
        problems: s.anomalies.filter((a) => a.kind === 'transaction').slice(0, 2).map((a) => `${a.title} — ${a.detail}`),
        actions: ['Large one-off purchases are the fastest way to move a month’s result; plan them against the Forecast page.'],
        followUps: [SUGGESTED_QUESTIONS[0], SUGGESTED_QUESTIONS[1]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'merchant': {
      const key = merchantKey(merchant as string);
      const all = s.txs.filter((x) => merchantKey(x.merchant) === key);
      const rows = s.rangeTx.filter((x) => merchantKey(x.merchant) === key);
      const total = round2(rows.reduce((a, x) => a + x.amount, 0));
      const allTotal = round2(all.reduce((a, x) => a + x.amount, 0));
      const last = [...all].sort((a, b) => b.date.localeCompare(a.date))[0];
      return base({
        headline: `${merchant}: ${money(total)} in ${period} across ${plural(rows.length, 'transaction')}.`,
        observations: [`Across all your data: ${money(allTotal)} over ${plural(all.length, 'transaction')}, averaging ${money(allTotal / all.length)}.`, `Most recent: ${money(last.amount)} on ${fmtDate(last.date)} (${last.category}).`],
        numbers: [{ label: period, value: money(total) }, { label: 'All time', value: money(allTotal) }, { label: 'Average', value: money(allTotal / all.length) }],
        patterns: [s.recurring.some((r) => merchantKey(r.merchant) === key) ? 'This is a recurring payment.' : 'This is not a regular monthly charge.'],
        problems: [],
        actions: ['Search for this merchant on the Transactions page to see every entry.'],
        followUps: [SUGGESTED_QUESTIONS[0], SUGGESTED_QUESTIONS[3]],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'balance': {
      const first = s.monthly[0];
      const last3 = s.monthly.slice(-3);
      return base({
        basis: 'Opening balance plus every recorded transaction',
        headline: `Your balance is ${money(s.balanceNow)}.`,
        observations: [`It has changed by ${moneySigned(s.balanceNow - (first?.opening ?? s.balanceNow))} since your first recorded month, ${monthLabel(first?.month ?? s.focusMonth)}.`],
        numbers: last3.map((x) => ({ label: `${monthLabel(x.month)} ${x.inProgress ? '(today)' : 'closing'}`, value: money(x.closing) })),
        patterns: [`Average monthly change over these months: ${moneySigned(last3.reduce((a, x) => a + x.net, 0) / Math.max(1, last3.length))}.`],
        problems: s.balanceNow < 0 ? ['Your balance is negative.'] : [],
        actions: ['Balance = opening balance (set in Settings) + income − spending. Adjust the opening balance if it does not match your bank.'],
        followUps: [SUGGESTED_QUESTIONS[6], 'What does next month look like?'],
      });
    }

    /* -------------------------------------------------------------------- */
    case 'anomaly': {
      return base({
        headline: s.anomalies.length ? `I found ${plural(s.anomalies.length, 'unusual item')} in ${period}.` : `Nothing unusual in ${period}.`,
        observations: s.anomalies.slice(0, 4).map((a) => `${a.title}. ${a.detail}`),
        numbers: s.anomalies.slice(0, 4).map((a) => ({ label: a.title, value: `${moneySigned(a.excess)} vs normal`, tone: 'bad' as const })),
        patterns: ['A purchase is unusual when it is at least twice your typical purchase in that category; a category is unusual when it runs 30% above its three-month average.'],
        problems: [],
        actions: s.anomalies.length ? ['Check each item is a purchase you recognise. One-offs are fine — repeated ones become a habit.'] : ['No action needed.'],
        followUps: [SUGGESTED_QUESTIONS[1], SUGGESTED_QUESTIONS[0]],
      });
    }

    /* -------------------------------------------------------------------- */
    default: {
      const top = s.categories[0];
      return base({
        headline: 'I could not match that to an analysis I can run, so here is where you stand.',
        observations: [
          `${period}${toDate}: ${money(t.income)} in, ${money(t.expenses)} out, ${moneySigned(t.net)} net.`,
          top ? `Largest category: ${top.category} at ${money(top.amount)} (${pct(top.share, 0)}).` : '',
          `Financial health score: ${s.health.score}/100.`,
        ].filter(Boolean),
        numbers: [
          { label: 'Balance', value: money(s.balanceNow) },
          { label: 'Savings rate', value: pct(t.savingsRate) },
        ],
        patterns: [],
        problems: [],
        actions: ['I answer questions about spending by category or merchant, changes between periods, savings potential, subscriptions, budgets, cash flow, forecasts and your health score. Try one of the suggestions below.'],
        followUps: SUGGESTED_QUESTIONS.slice(0, 4),
      });
    }
  }
}
